"""Generate Apgi/Spec.lean from specification/parameters.json.

Contract (plan edit C2):
  * Emits DEFINITIONS AND CONSTANTS ONLY. Never proofs.
  * Only parameters with a non-null `lean_name` and an exact `value` are emitted.
  * Values are emitted as exact rationals, so 0.5 becomes 1 / 2, never a float.
  * The registry hash and spec version are embedded; proofs that import
    Apgi.Spec are thereby tied to one registry revision.
  * `--check` exits 1 if the committed Spec.lean differs from a fresh render.
    CI runs `--check`, so a registry edit without regeneration fails the build.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

from registry import ROOT, exact, load, registry_hash

OUT = ROOT / "Apgi" / "Spec.lean"


def lean_rat(value: str) -> str:
    q = exact(value)
    return str(q.numerator) if q.denominator == 1 else f"{q.numerator} / {q.denominator}"


def render() -> str:
    spec = load("parameters.json")
    lines = [
        "module",
        "",
        "public import Mathlib.Basic.Real.Basic",
        "",
        "/-!",
        "# APGI canonical constants — GENERATED, DO NOT EDIT",
        "",
        "Generated by `verification/python/generate_lean.py` from",
        "`specification/parameters.json`. Edit the registry, then regenerate.",
        "CI fails if this file is out of date (`generate_lean.py --check`).",
        "-/",
        "",
        "@[expose] public section",
        "",
        "namespace Apgi",
        "",
        f'/-- Registry version this file was generated from. -/',
        f'def specVersion : String := "{spec["spec_version"]}"',
        "",
        "/-- SHA-256 of the specification files this file was generated from. -/",
        f'def specHash : String := "{registry_hash()}"',
        "",
    ]
    for p in spec["parameters"]:
        if not p.get("lean_name") or p.get("value") is None:
            continue
        lines += [
            f'/-- `{p["id"]}` ({p["unit"]}) — {p["source"]}, role: {p["role"]}. -/',
            f'noncomputable def {p["lean_name"]} : ℝ := {lean_rat(p["value"])}',
            "",
        ]
    lines += ["end Apgi", "", "end", ""]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8").replace("\r\n", "\n") if OUT.exists() else ""
        if current != text:
            print("Apgi/Spec.lean is stale: run verification/python/generate_lean.py", file=sys.stderr)
            return 1
        print("Apgi/Spec.lean is in sync with the registry")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
