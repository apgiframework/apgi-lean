"""Render the requirement → proof traceability matrix and the assumption inventory.

  python make_traceability.py --check  exit 1 if any generated file is stale
  python make_traceability.py          writes docs/traceability-matrix.md,
                                       docs/assumption-inventory.md and
                                       verification/reports/traceability.csv

Everything is generated from specification/*.json and the Lean sources; a hand edit is
overwritten on the next run, and test_traceability.py fails if the files are stale.
"""
from __future__ import annotations

import csv
import io
import re
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import check_consistency as CC  # noqa: E402
from registry import ROOT, load, registry_hash  # noqa: E402

DOCS = ROOT / "docs"
MATRIX = DOCS / "traceability-matrix.md"
INVENTORY = DOCS / "assumption-inventory.md"
CSV_OUT = ROOT / "verification" / "reports" / "traceability.csv"


def lean_hypotheses() -> list[tuple[str, str, str]]:
    """Structures whose fields are the hypotheses of the trajectory theorems, and Prop-valued
    definitions that state registered hypotheses (never proved)."""
    out = []
    for f in sorted((ROOT / "Apgi").glob("*.lean")):
        text = f.read_text(encoding="utf-8")
        for m in re.finditer(r"/-- ((?:(?!-/).)*?) -/\s*structure (\w+) \(p : PipeParams\) : Prop where\n((?:  [^\n]*\n)+)", text, re.S):
            fields = [ln.strip() for ln in m.group(3).splitlines() if ln.strip()]
            out.append((f.name, m.group(2), "; ".join(fields)))
        for m in re.finditer(r"/-- ((?:(?!-/).)*?) -/\s*def (H10Ordering)", text, re.S):
            out.append((f.name, m.group(2), " ".join(m.group(1).split())))
    return out


def build() -> dict[str, str]:
    Q = load("requirements.json")["requirements"]
    E = {e["id"]: e for e in load("equations.json")["equations"]}
    C = {c["id"]: c for c in load("epistemic-claims.json")["claims"]}
    B = load("bridges.json")
    thms = CC.lean_theorems()
    rh = registry_hash()

    # CSV matrix: one row per (requirement, evidence item)
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(["requirement", "ssot", "kind", "status", "conformance_test", "evidence_type", "evidence"])
    for r in Q:
        items = [("lean", n) for n in r["lean"]] + [("test", t) for t in r["tests"]] + \
                [("equation", e) for e in r["equations"]] + [("claim", c) for c in r["claims"]]
        for typ, ev in items or [("none", "")]:
            w.writerow([r["id"], r["ssot"], r["kind"], r["status"], r["conformance_test"] or "", typ, ev])
    csv_text = buf.getvalue()

    kinds = Counter(r["kind"] for r in Q)
    sts = Counter(r["status"] for r in Q)
    tc = [r for r in Q if r["id"].startswith("REQ-TC-")]
    tc_st = Counter(r["status"] for r in tc)
    eq_with_thm = sum(1 for e in E.values() if any(n in thms for n in e["lean"]))
    claim_st = Counter(c["status"] for c in C.values())

    L = ["# APGI requirement → proof traceability matrix", "",
         f"Generated by `verification/python/make_traceability.py` from registry hash `{rh[:16]}…`. Do not edit by hand.", "",
         "A Lean proof establishes a consequence of a definition; it is never evidence that APGI describes the brain (SSOT §3.4). "
         "Coverage is not correctness.", "",
         "## Coverage (numerator / denominator)", "",
         f"- Lean theorems: {len(thms)}, all axiom-pinned (TC-22).",
         f"- Registered equations with at least one Lean theorem: {eq_with_thm} / {len(E)}.",
         f"- Conformance tests TC-01…TC-26: {tc_st['pass']} pass, {tc_st['partial']} partial, {tc_st['not-implemented']} not implemented (of {len(tc)}).",
         f"- Requirements: {len(Q)} ({', '.join(f'{k} {v}' for k, v in sorted(kinds.items()))}); "
         f"status {', '.join(f'{k} {v}' for k, v in sorted(sts.items()))}.",
         f"- Claims: {len(C)} ({', '.join(f'{k} {v}' for k, v in sorted(claim_st.items()))}).", "",
         "Kinds: **proved** (Lean theorem), **conditional** (Lean theorem under an explicit extra hypothesis), "
         "**tested** (numerical test), **assumed** (model or bridge assumption), **empirical** (needs data).", "",
         "## Requirements", ""]
    for r in Q:
        L.append(f"### {r['id']} — {r['status']} ({r['kind']})")
        L.append("")
        L.append(f"- SSOT: {r['ssot']}" + (f"; conformance test {r['conformance_test']}" if r["conformance_test"] else ""))
        L.append(f"- Requirement: {r['requirement']}")
        if r["equations"]:
            L.append(f"- Equations: {', '.join(r['equations'])}")
        if r["claims"]:
            L.append("- Claims: " + ", ".join(f"{c} ({C[c]['status']})" for c in r["claims"]))
        if r["lean"]:
            L.append("- Lean: " + ", ".join(f"`{n}`" for n in r["lean"]))
        if r["tests"]:
            L.append("- Tests: " + ", ".join(f"`{t}`" for t in r["tests"]))
        if r["limitation"]:
            L.append(f"- Limitation: {r['limitation']}")
        L.append("")
    if (ROOT / "specification" / "hypotheses.json").exists():
        H = load("hypotheses.json")
        T, PR = H["table"], H["predictions"]
        L += [f"## Registered predictions ({T['id']}, {T['title']}; TC-26 first slice)", "",
              f"{len(PR)} rows, {sum(len(p['codes']) for p in PR)} prediction codes, cells verbatim from {T['source']} "
              f"pp. {T['first_page']}–{T['last_page']} and verified against the pinned PDF by `extract_sources.py`. "
              "Tier and label are read literally from the Severity cell; no classification is derived.", ""]
        for p in PR:
            tag = " · ".join(x for x in (f"tier {p['severity_tier']}" if p["severity_tier"] else "", p["label"] or "") if x)
            L.append(f"- **{p['pred_id']}** ({p['protocol']}; {tag}): {p['construct']}. "
                     f"Standard: {p['classification_standard']}. HEP-dependent: {p['hep_dependent']}.")
        L.append("")
    matrix = "\n".join(L).rstrip() + "\n"

    A = ["# APGI assumption inventory", "",
         f"Generated by `verification/python/make_traceability.py` from registry hash `{rh[:16]}…`. Do not edit by hand.", "",
         "Every result in this repository holds only under the assumptions listed here. Nothing below is proved to hold of "
         "a brain; the bridges and hypotheses are exactly the places where APGI makes contact with data.", "",
         "## 1. Hypotheses of the Lean trajectory theorems", ""]
    for f, name, body in lean_hypotheses():
        A.append(f"- `{name}` ({f}): {body}")
    A += ["", "## 2. Theorem preconditions checked against registry ranges (TC-23)", ""]
    for e in E.values():
        for p in e.get("preconditions", []):
            rhs = p.get("param_rhs", p.get("value"))
            A.append(f"- {e['id']}: {p['param']} {p['op']} {rhs}{(' × ' + p['scale']) if p.get('scale') else ''} — {p['theorem']}")
    A += ["", "## 3. Conditional, assumed and empirical requirements", ""]
    for r in Q:
        if r["kind"] in ("conditional", "assumed", "empirical"):
            A.append(f"- {r['id']} ({r['kind']}, {r['status']}): {r['requirement']} {r['limitation'] or ''}".rstrip())
    A += ["", "## 4. Claims that are assumed or unresolved", ""]
    for c in C.values():
        if c["status"] in ("assumed", "unresolved"):
            A.append(f"- {c['id']} ({c['status']}): {c['text']}")
    A += ["", "## 5. Bridge and measurement assumptions (bridges.json)", ""]
    for b in B["bridges"]:
        fal = b["falsifier"] or f"none registered — {b['falsifier_unresolved_reason']}"
        A.append(f"- {b['id']} ({b['status']}; {', '.join(b['tiers'])}): {b['statement']} Falsifier: {fal}")
    for o in B["observables"]:
        A.append(f"- {o['id']}: {o['construct']} ← {o['candidate']}. Limitation: {o['limitation']}. Validated: {'yes' if o['validated'] else 'no'}.")
    A += ["", "## 6. Open conflicts and divergences (known-conflicts.json)", ""]
    K = load("known-conflicts.json")
    for k in K["conflicts"]:
        if k["status"] == "open":
            A.append(f"- {k['id']}: {k.get('summary') or k.get('detail') or k['check']}")
    for key in ("production", "production_secondary"):
        for d in K.get(key, {}).get("divergences", []):
            if d.get("status") in ("open", "declared_variant"):
                A.append(f"- {d['id']} ({d['status']}, {K[key]['repository']}): {d.get('summary', '')}".rstrip())
    inventory = "\n".join(A).rstrip() + "\n"
    return {str(MATRIX): matrix, str(INVENTORY): inventory, str(CSV_OUT): csv_text}


def main() -> int:
    if "--check" in sys.argv:
        stale = [p for p, t in build().items() if not Path(p).exists() or
                 Path(p).read_text(encoding="utf-8").replace("\r\n", "\n") != t]
        for p in stale:
            print(f"STALE {Path(p).relative_to(ROOT)}: run python verification/python/make_traceability.py")
        return 1 if stale else 0
    for path, text in build().items():
        Path(path).parent.mkdir(parents=True, exist_ok=True)
        Path(path).write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {Path(path).relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
