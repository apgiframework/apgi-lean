"""Regenerate the registry-derived parts of the APGI Single Source of Truth (task 57, D10; TC-21).

The SSOT (framework v1.2 working draft) is kept outside version control in docs/apgi-v-1-2/ and
pinned by sha256 as SRC-SSOT-V12D. Its header and its verification sections quote counts that the
registry owns (spec version, theorems, equations, claims, requirements, conformance tests, golden
vectors). Hand-maintained, they went stale (D10). This script rewrites exactly those parts:

  * the header row "Registry version";
  * the golden-vector paragraph of "Computational verification and golden vectors";
  * the status table, theorem register, claim register and open-targets paragraph of
    "Lean 4 formal verification".

Each generated part is delimited by HTML comment markers (<!-- BEGIN GENERATED: name --> …
<!-- END GENERATED: name -->); the header row is matched by its first cell. Everything else in the
document is left byte for byte unchanged.

No registry hash is written into the SSOT: the SSOT is itself a pinned registry source
(source-manifest.json), so embedding the hash would be circular. The hash lives in Apgi/Spec.lean
and the release manifest.

Usage:
    python make_ssot_tables.py            rewrite every SSOT copy found (see SSOT_PATHS)
    python make_ssot_tables.py --check    exit 1 if any copy differs from the registry
A rewrite of docs/apgi-v-1-2/ re-pins SRC-SSOT-V12D in source-manifest.json; then re-run
extraction and generate_lean.py (verify_all.ps1 does both, in that order).
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from collections import Counter
from pathlib import Path

import check_consistency as CC
from registry import ROOT, load

SSOT_PATHS = (ROOT / "docs" / "apgi-v-1-2" / "APGI-Single-Source-of-Truth.md",
              ROOT / "docs" / "APGI-Single-Source-of-Truth.md")
GOLDEN = ROOT / "verification" / "python" / "golden_vectors.json"
LEAN_DIR = ROOT / "Apgi"

HEADER_ROW = "| **Registry version** |"


def esc(text: str) -> str:
    """Escape for the SSOT's markdown dialect (docx export: \\_ and \\| inside table cells)."""
    return text.replace("\\", "\\\\").replace("_", "\\_").replace("|", "\\|")


def short(name: str) -> str:
    return name.removeprefix("Apgi.")


def facts() -> dict:
    P = load("parameters.json")
    E = load("equations.json")["equations"]
    C = load("epistemic-claims.json")["claims"]
    Q = load("requirements.json")["requirements"]
    thms, aud = CC.lean_theorems(), CC.audited()
    per_module = {}
    for f in sorted(LEAN_DIR.glob("*.lean")):
        n = len(re.findall(r"^theorem\s+\S+", f.read_text(encoding="utf-8"), re.M))
        if n:
            per_module[f.stem] = n
    g = json.loads(GOLDEN.read_text(encoding="utf-8"))
    fams = {k: len(v) for k, v in g.items() if k != "_meta"}
    manifest = json.loads((ROOT / "lake-manifest.json").read_text(encoding="utf-8"))
    mathlib = next((p for p in manifest["packages"] if p["name"] == "mathlib"), {})
    tc = [r for r in Q if r["id"].startswith("REQ-TC-")]
    return dict(spec=P["spec_version"], E=E, C=C, Q=Q, thms=thms, aud=aud, per_module=per_module,
                fams=fams, golden_meta=g.get("_meta", {}),
                toolchain=(ROOT / "lean-toolchain").read_text(encoding="utf-8").strip(),
                mathlib=mathlib.get("inputRev") or mathlib.get("rev", "?"),
                tc=tc)


def counts(c: Counter, order=None) -> str:
    keys = order or sorted(c)
    return ", ".join(f"{c[k]} {k}" for k in keys if c[k])


def header_row(F) -> str:
    return (f"{HEADER_ROW} apgi-lean specification {F['spec']} · registry hash recorded in Apgi/Spec.lean and "
            f"verification/reports/release-manifest.json (not repeated here: this document is itself a pinned "
            f"registry source) |")


def block_golden(F) -> list[str]:
    fams = F["fams"]
    listing = ", ".join(f"{esc(k)} ({v})" for k, v in fams.items())
    dps = F["golden_meta"].get("mp_dps", "?")
    return [f"verification/python/golden\\_vectors.json, generated by make\\_golden.py at {dps}-digit precision, "
            f"holds {sum(fams.values())} vectors in {len(fams)} families: {listing}. Each vector records input, "
            f"configuration, expected output, units, tolerance and source; test\\_golden\\_vectors.py checks "
            f"apgi\\_ref.py against every one."]


def block_status(F) -> list[str]:
    E, C, Q, thms, aud = F["E"], F["C"], F["Q"], F["thms"], F["aud"]
    eq_with = sum(1 for e in E if any(n in thms for n in e["lean"]))
    tc_st = Counter(r["status"] for r in F["tc"])
    mods = "; ".join(f"Apgi/{m}.lean ({n})" for m, n in F["per_module"].items())
    return [
        "| Item | Value |",
        "| ----- | ----- |",
        "| **Repository** | github.com/apgiframework/apgi-lean, branch main |",
        f"| **Toolchain** | {esc(F['toolchain'])}; Mathlib {esc(F['mathlib'])} (lake-manifest pin) |",
        f"| **Specification** | version {F['spec']}; Apgi/Spec.lean generated from the registry (specification/\\*.json) and hash-pinned |",
        f"| **Modules** | {len(F['per_module'])} modules with theorems: {mods} |",
        "| **Build** | lake build \\--wfail must pass (any sorry or warning fails the build); CI job “Lean” |",
        f"| **Axiom audit** | {len(aud & thms)} of {len(thms)} theorems pinned with \\#guard\\_msgs; allowed axioms \\[propext, Classical.choice, Quot.sound\\] or a subset; no sorry, no admit, no axiom declaration |",
        f"| **Equations** | {eq_with} of {len(E)} registered equations have at least one Lean theorem |",
        f"| **Claims** | {len(C)} (CL-1…CL-{len(C)}): {counts(Counter(c['status'] for c in C))} |",
        f"| **Requirements** | {len(Q)}: {counts(Counter(r['status'] for r in Q))} |",
        f"| **Conformance tests** | TC-01…TC-{len(F['tc']):02d}: {counts(tc_st, ['pass', 'partial', 'not-implemented'])} |",
        f"| **Golden vectors** | {sum(F['fams'].values())} in {len(F['fams'])} families |",
        "| **Results per run** | verification/reports/verification-report.md (CI artifact) and docs/VERIFICATION-REPORT.md; not frozen in this document |",
    ]


def block_theorems(F) -> list[str]:
    thms = F["thms"]
    by_eq = {}
    for c in F["C"]:
        for e in c.get("equations", []):
            by_eq.setdefault(e, []).append(c["id"])
    out = ["| Equation | Theorems | Claim |", "| ----- | ----- | ----- |"]
    for e in F["E"]:
        names = [short(n) for n in e["lean"] if n in thms]
        if not names:
            continue
        cl = ", ".join(by_eq.get(e["id"], [])) or "—"
        out.append(f"| **{e['id']}** | {esc('; '.join(names))} | {cl} |")
    return out


def block_claims(F) -> list[str]:
    out = ["| Claim | Statement | Status |", "| ----- | ----- | ----- |"]
    for c in F["C"]:
        text = " ".join(c["text"].split())
        out.append(f"| **{c['id']}** | {esc(text)} | {c['status']} |")
    return out


def block_targets(F) -> list[str]:
    open_ = [c for c in F["C"] if c["status"] != "proved"]
    items = "; ".join(f"{c['id']} ({c['status']})" for c in open_)
    return [f"**Open targets (from the claim register):** {items}. Every other claim is proved in Lean; "
            "a proved claim establishes a consequence of the definitions, never that APGI describes the brain."]


BLOCKS = {"golden-vectors": block_golden, "lean-status": block_status, "theorem-register": block_theorems,
          "claim-register": block_claims, "open-targets": block_targets}


def render(text: str, F) -> str:
    lines = text.split("\n")
    out, i = [], 0
    while i < len(lines):
        line = lines[i]
        if line.startswith(HEADER_ROW):
            out.append(header_row(F))
            i += 1
            continue
        m = re.fullmatch(r"<!-- BEGIN GENERATED: (\S+) -->", line.strip())
        if m:
            name = m.group(1)
            if name not in BLOCKS:
                raise SystemExit(f"unknown generated block {name!r}")
            end = f"<!-- END GENERATED: {name} -->"
            j = next((k for k in range(i + 1, len(lines)) if lines[k].strip() == end), None)
            if j is None:
                raise SystemExit(f"block {name!r} has no END marker")
            out += [line, *BLOCKS[name](F), lines[j]]
            i = j + 1
            continue
        out.append(line)
        i += 1
    return "\n".join(out)


def _pin_entry():
    man = ROOT / "specification" / "source-manifest.json"
    text = man.read_text(encoding="utf-8")
    return man, text, next(s for s in json.loads(text)["sources"] if s["id"] == "SRC-SSOT-V12D")


def pin_current(path: Path) -> bool:
    import hashlib

    return _pin_entry()[2]["sha256"] == hashlib.sha256(path.read_bytes()).hexdigest()


def repin(path: Path) -> None:
    """Move the SRC-SSOT-V12D sha256 pin in source-manifest.json to the rewritten draft, so that
    extraction keeps finding it. The SSOT holds no registry hash, so this does not loop."""
    import hashlib

    man, text, entry = _pin_entry()
    new = hashlib.sha256(path.read_bytes()).hexdigest()
    if entry["sha256"] != new:
        assert text.count(entry["sha256"]) == 1
        man.write_text(text.replace(entry["sha256"], new), encoding="utf-8", newline="")
        print(f"re-pinned SRC-SSOT-V12D {entry['sha256'][:12]}… -> {new[:12]}…")


def markers_present(text: str) -> set[str]:
    return set(re.findall(r"<!-- BEGIN GENERATED: (\S+) -->", text))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    F = facts()
    found, bad = 0, 0
    for p in SSOT_PATHS:
        if not p.exists():
            continue
        found += 1
        raw = p.read_bytes()
        crlf = b"\r\n" in raw
        text = raw.decode("utf-8").replace("\r\n", "\n")
        missing = set(BLOCKS) - markers_present(text)
        if missing or HEADER_ROW not in text:
            print(f"{p}: missing generated blocks {sorted(missing)}{'' if HEADER_ROW in text else ' and the header row'}")
            bad += 1
            continue
        new = render(text, F)
        if new == text:
            print(f"{p.relative_to(ROOT)} is current")
            continue
        if a.check:
            print(f"{p.relative_to(ROOT)} is stale: run make_ssot_tables.py")
            bad += 1
        else:
            p.write_bytes((new.replace("\n", "\r\n") if crlf else new).encode("utf-8"))
            print(f"wrote {p.relative_to(ROOT)}")
    if SSOT_PATHS[0].exists():
        if a.check:
            if not pin_current(SSOT_PATHS[0]):
                print("SRC-SSOT-V12D pin is stale: run make_ssot_tables.py")
                bad += 1
        else:
            repin(SSOT_PATHS[0])
    if not found:
        print("no SSOT copy present (the v1.2 drafts are not under version control); nothing to check")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
